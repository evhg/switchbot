import { timingSafeEqual } from '../../../packages/core/src/health/signature.ts';
import { serviceKeys } from './env.ts';
import { HttpError } from './http.ts';
import type { Db } from './supabase.ts';

function bearer(req: Request): string | null {
  const h = req.headers.get('authorization');
  const m = h?.match(/^Bearer\s+(.+)$/i);
  return m ? m[1]!.trim() : null;
}

// Positive cron-secret checks are cached per worker for a few minutes, so the every-minute poll doesn't add
// a database round trip to every call. Only a value that already verified is cached.
const CRON_CACHE_MS = 5 * 60_000;
let cronOk: { secret: string; at: number } | null = null;

/**
 * Scheduled / internal calls. Accepted credentials:
 *   - `x-cron-secret`: pg_cron sends the Vault secret `cron_secret` (generated by migration 0002). It is checked
 *     against the CRON_SECRET function secret when one is set, otherwise against Vault through the
 *     public.verify_cron_secret() RPC (security definer, service_role only), so no manual setup is needed.
 *   - the project's service key (legacy service-role JWT or an `sb_secret_…` key) as a Bearer token or `apikey`.
 */
export async function isCronRequest(req: Request, db: Db): Promise<boolean> {
  const got = req.headers.get('x-cron-secret');
  if (got) {
    const configured = Deno.env.get('CRON_SECRET');
    if (configured && timingSafeEqual(got, configured)) return true;
    if (cronOk && Date.now() - cronOk.at < CRON_CACHE_MS && timingSafeEqual(got, cronOk.secret)) return true;
    if (got.length >= 32 && got.length <= 256) {
      const { data, error } = await db.rpc('verify_cron_secret', { p_secret: got });
      if (error) console.error('verify_cron_secret', error.message);
      if (data === true) {
        cronOk = { secret: got, at: Date.now() };
        return true;
      }
    }
  }
  const keys = serviceKeys();
  const tok = bearer(req);
  const apikey = req.headers.get('apikey');
  return keys.some((k) => (tok !== null && timingSafeEqual(tok, k)) || (apikey !== null && timingSafeEqual(apikey, k)));
}

export async function requireCron(req: Request, db: Db): Promise<void> {
  if (!(await isCronRequest(req, db))) throw new HttpError(401, 'unauthorized');
}

/**
 * Cron/service, or a signed-in household owner/member (e.g. a "sync now" / "regenerate" button in the PWA).
 * 'viewer' members are read-only and get 403: every caller of this triggers writes, API calls or pushes.
 */
export async function requireCronOrMember(req: Request, db: Db): Promise<'cron' | string> {
  if (await isCronRequest(req, db)) return 'cron';
  const tok = bearer(req);
  if (!tok) throw new HttpError(401, 'unauthorized');
  const { data, error } = await db.auth.getUser(tok);
  if (error || !data.user) throw new HttpError(401, 'unauthorized');
  const m = await db.from('household_members').select('user_id,role').eq('user_id', data.user.id).maybeSingle();
  if (m.error || !m.data) throw new HttpError(403, 'not a household member');
  const role = (m.data as { role?: string }).role;
  if (role !== 'owner' && role !== 'member') throw new HttpError(403, 'read-only household role');
  return data.user.id;
}

/** Shared secret from the last path segment or ?token= (for webhooks that can't sign requests). */
export function urlSecretMatches(req: Request, expected: string): boolean {
  const url = new URL(req.url);
  const last = url.pathname.split('/').filter(Boolean).pop() ?? '';
  const q = url.searchParams.get('token') ?? '';
  return (q !== '' && timingSafeEqual(q, expected)) || (last !== '' && timingSafeEqual(last, expected));
}
