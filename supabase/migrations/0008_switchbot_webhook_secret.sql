-- SwitchBot webhook path secret, generated in Vault so registration needs no manual step.
--
--   * `switchbot_webhook_secret` (32 random bytes, hex) is created once if it doesn't exist. It is the last
--     path segment of https://<ref>.supabase.co/functions/v1/switchbot-webhook/<secret>.
--   * public.verify_switchbot_webhook_secret(text): lets switchbot-webhook check a path segment without reading
--     the secret (SHA-256 digest compare, like verify_cron_secret in 0002).
--   * public.switchbot_webhook_secret(): returns the value, for switchbot-admin, which has to build the URL it
--     registers with SwitchBot.
-- Both are security definer and executable by service_role only (not anon / authenticated), so they are not
-- reachable through the public API with the publishable key or a user session.
--
-- Rotation: vault.update_secret(<id>, encode(extensions.gen_random_bytes(32), 'hex')) for this name, then call
-- switchbot-admin {"action":"register-webhook"} (see docs/BACKEND.md, "SwitchBot webhook").

create extension if not exists pgcrypto with schema extensions;

do $$
begin
  if not exists (select 1 from vault.secrets where name = 'switchbot_webhook_secret') then
    perform vault.create_secret(
      encode(extensions.gen_random_bytes(32), 'hex'),
      'switchbot_webhook_secret',
      'Last path segment of the SwitchBot webhook URL. Generated by migration 0008.'
    );
  end if;
end $$;

create or replace function public.verify_switchbot_webhook_secret(p_secret text) returns boolean
language sql stable security definer set search_path = '' as $$
  select coalesce(
    length(p_secret) >= 32 and exists (
      select 1 from vault.decrypted_secrets ds
      where ds.name = 'switchbot_webhook_secret'
        and extensions.digest(ds.decrypted_secret, 'sha256') = extensions.digest(p_secret, 'sha256')
    ),
    false
  )
$$;
revoke all on function public.verify_switchbot_webhook_secret(text) from public, anon, authenticated;
grant execute on function public.verify_switchbot_webhook_secret(text) to service_role;

create or replace function public.switchbot_webhook_secret() returns text
language sql stable security definer set search_path = '' as $$
  select ds.decrypted_secret from vault.decrypted_secrets ds where ds.name = 'switchbot_webhook_secret' limit 1
$$;
revoke all on function public.switchbot_webhook_secret() from public, anon, authenticated;
grant execute on function public.switchbot_webhook_secret() to service_role;
